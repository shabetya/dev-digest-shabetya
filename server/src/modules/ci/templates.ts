import { execFileSync } from 'node:child_process';
import { stringify as stringifyYaml } from 'yaml';
import type { Agent, CiExportInput, CiFile } from '@devdigest/shared';

/**
 * Generated-file templates for the Export Wizard (AC-2). Every file is built
 * by serializing a plain JS object through the `yaml`/`JSON` libraries —
 * NEVER by string-concatenating agent name / repo / system-prompt content
 * into a hand-written YAML template. That's load-bearing: `yaml.stringify`
 * quotes/escapes anything that would otherwise break YAML structure, so a
 * crafted agent name or system prompt can never inject an extra workflow
 * step or widen `permissions:` (security skill, A05 — see PLAN-05's
 * Constraints section).
 */

const PINNED_ACTIONS = {
  checkout: 'actions/checkout@v4',
  setupNode: 'actions/setup-node@v4',
  uploadArtifact: 'actions/upload-artifact@v4',
} as const;

/** `.devdigest/agents/<slug>.yaml` — conforms to `AgentManifest` (AC-2). */
export function buildAgentManifestYaml(agent: Agent, skillSlugs: string[]): string {
  const manifest = {
    name: agent.name,
    provider: agent.provider,
    model: agent.model,
    system_prompt: agent.system_prompt,
    skills: skillSlugs,
    strategy: agent.strategy,
    ci_fail_on: agent.ci_fail_on,
  };
  return `# Generated by DevDigest — safe to edit before merging.\n${stringifyYaml(manifest)}`;
}

/** `.devdigest/skills/<slug>.md` — one per linked skill (AC-2). */
export function buildSkillMarkdown(name: string, body: string): string {
  return `# ${name}\n\n${body}`;
}

/**
 * `.devdigest/memory.jsonl` — empty placeholder (AC-2 requires the file to
 * exist in the generated set; this starter has no per-agent curated-memory
 * selection mechanism yet to seed it from, so it's generated empty rather
 * than fabricated. `agent-runner` tolerates a missing/empty file the same way).
 */
export function buildMemoryJsonl(): string {
  return '';
}

/** Best-effort HEAD sha of THIS devdigest repo, for the pinned second checkout. Falls back to `main` if git is unavailable (e.g. no `.git` in the deployment). */
export function resolveDevdigestHeadSha(): string {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch {
    return 'main';
  }
}

export interface WorkflowYamlInput {
  devdigestRepo: string;
  pinnedSha: string;
  agentSlug: string;
  triggers: CiExportInput['triggers'];
  postAs: CiExportInput['post_as'];
}

/**
 * AC-2 fix: the Preview step's workflow-YAML edit must actually take effect
 * on Install (PR) and in the downloaded zip — not be silently discarded in
 * favor of the freshly regenerated default. `workflow_yaml_override` is
 * used verbatim when it's present and a non-empty string; no full
 * YAML-schema validation is attempted (not required by the fix), just
 * enough of a check that garbage input can't crash generation.
 */
function resolveWorkflowYaml(input: CiExportInput, generated: WorkflowYamlInput): string {
  const override = input.workflow_yaml_override;
  if (typeof override === 'string' && override.trim().length > 0) return override;
  return buildWorkflowYaml(generated);
}

/**
 * `.github/workflows/devdigest-review.yml` (AC-2). Hardcodes the
 * security-critical shape (AC-3/AC-4/AC-21) — minimal `permissions:`,
 * `pull_request`-only trigger, pinned major-version action tags matching
 * `.github/workflows/evals.yml`'s own convention — then layers the user's
 * triggers/post_as choices on top. Returned as a user-EDITABLE string
 * (`CiFile.editable: true`); Preview lets the user change it before Install.
 */
export function buildWorkflowYaml(input: WorkflowYamlInput): string {
  const workflow = {
    name: 'DevDigest Review',
    on: {
      pull_request: {
        types: input.triggers,
      },
    },
    // AC-3: exactly these two scopes, nothing else.
    permissions: {
      contents: 'read',
      'pull-requests': 'write',
    },
    jobs: {
      review: {
        'runs-on': 'ubuntu-latest',
        'timeout-minutes': 15,
        steps: [
          {
            name: 'Checkout PR',
            uses: PINNED_ACTIONS.checkout,
          },
          {
            name: 'Checkout devdigest (agent-runner)',
            uses: PINNED_ACTIONS.checkout,
            with: {
              repository: input.devdigestRepo,
              ref: input.pinnedSha,
              path: '.devdigest-runner',
            },
          },
          {
            name: 'Setup Node',
            uses: PINNED_ACTIONS.setupNode,
            with: { 'node-version': '22' },
          },
          {
            name: 'Run DevDigest review',
            run: 'node .devdigest-runner/agent-runner/dist/index.js',
            env: {
              // GitHub Actions expressions — static, trusted text (never
              // interpolated agent/repo data); fork PRs simply find these
              // secrets empty (GitHub's own default), which is exactly what
              // AC-9 relies on.
              OPENROUTER_API_KEY: '${{ secrets.OPENROUTER_API_KEY }}',
              GITHUB_TOKEN: '${{ secrets.GITHUB_TOKEN }}',
              AGENT_MANIFEST_PATH: `.devdigest/agents/${input.agentSlug}.yaml`,
              POST_AS: input.postAs,
            },
          },
          {
            name: 'Upload result artifact',
            if: 'always()',
            uses: PINNED_ACTIONS.uploadArtifact,
            with: {
              name: 'devdigest-result',
              path: 'devdigest-result.json',
              'if-no-files-found': 'ignore',
            },
          },
        ],
      },
    },
  };
  return stringifyYaml(workflow);
}

/** Build the full generated-file set shown at Preview (AC-2). */
export function buildCiFiles(opts: {
  agent: Agent;
  agentSlug: string;
  skills: { slug: string; name: string; body: string }[];
  input: CiExportInput;
  devdigestRepo: string;
  pinnedSha: string;
}): CiFile[] {
  const files: CiFile[] = [
    {
      path: `.devdigest/agents/${opts.agentSlug}.yaml`,
      contents: buildAgentManifestYaml(opts.agent, opts.skills.map((s) => s.slug)),
      editable: true,
    },
    ...opts.skills.map((s) => ({
      path: `.devdigest/skills/${s.slug}.md`,
      contents: buildSkillMarkdown(s.name, s.body),
      editable: true,
    })),
    {
      path: '.devdigest/memory.jsonl',
      contents: buildMemoryJsonl(),
      editable: true,
    },
    {
      path: '.github/workflows/devdigest-review.yml',
      contents: resolveWorkflowYaml(opts.input, {
        devdigestRepo: opts.devdigestRepo,
        pinnedSha: opts.pinnedSha,
        agentSlug: opts.agentSlug,
        triggers: opts.input.triggers,
        postAs: opts.input.post_as,
      }),
      editable: true,
    },
  ];
  return files;
}
